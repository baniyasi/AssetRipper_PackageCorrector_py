#!/usr/bin/env python3
"""
Localization repair for AssetRipper-exported Unity projects.

TARGET VERSION
    ONLY for projects using:
        com.unity.localization   1.3.2
        com.unity.addressables   1.19.x
    Field names, YAML structure, and Addressable group format are hard-coded
    to match these versions. Running on other versions may silently corrupt
    Collection / SharedData files or produce unusable Addressable entries.

    If your project uses a different Localization version:
        - First inspect Library/PackageCache/com.unity.localization@<ver>/
          Samples~/*/String Table/*.asset to confirm Collection field names
          (m_SharedTableData, m_Tables, m_Extensions, m_Group, references.version).
        - Adjust build_collection_yaml() accordingly.
    If Addressables < 1.17:
        - Remove the 'FlaggedDuringContentUpdateRestriction' line added in
          phase6_addressables().

WHAT IT DOES
    Phase 0  Resolve Localization script-type GUIDs from PackageCache
    Phase 1  Move LocalizationSettings out of Resources (if needed)
    Phase 2  Scan SharedData / StringTable / Collection under Assets/localization
    Phase 3  Determine target GUID per table from scene/prefab TableReference
    Phase 4  Generate or repair one Collection per table (full 1.3.2 format)
    Phase 5  Align SharedData.meta / m_TCGuid / StringTable.m_SharedData
    Phase 6  Register every Localization asset in the Default Addressable group
    Phase 7  Optionally delete Localization folders under Assets/AssetBundles
             and clean up empty parents

REQUIREMENTS
    - Unity must be CLOSED before running.
    - Project folder must contain ExportedProject/.
    - No .bak files are created; changes are written in place.

NOT HANDLED
    - Dummy shaders generated by AssetRipper (//DummyShaderTextExporter).
      TMP / SDF rendering requires replacing them separately.
    - Runtime text that depends on TMPLocalizer filling LocalizeStringEvent
      at runtime: those values are not part of this repair.
"""

import os
import re
import secrets
import shutil
import tkinter as tk
from tkinter import filedialog, messagebox


# ---------- tkinter ----------
_tk_root = None

def _get_tk():
    global _tk_root
    if _tk_root is None:
        _tk_root = tk.Tk()
        _tk_root.withdraw()
    return _tk_root


def select_project_folder():
    _get_tk()
    initial = os.getcwd()
    while True:
        folder = filedialog.askdirectory(
            title="Select project folder (must contain ExportedProject)",
            initialdir=initial,
        )
        if not folder:
            return None
        folder = os.path.normpath(folder)
        if os.path.isdir(os.path.join(folder, 'ExportedProject')):
            return os.path.join(folder, 'ExportedProject')
        if os.path.basename(folder) == 'ExportedProject':
            return folder
        messagebox.showerror(
            "Invalid folder",
            f"The selected folder does not contain 'ExportedProject':\n{folder}",
        )
        initial = folder


# ---------- GUID helpers ----------
def read_meta_guid(p):
    try:
        with open(p, 'r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                if line.startswith('guid:'):
                    return line[5:].strip()[:32].lower()
    except OSError:
        pass
    return None


def read_script_guid(p):
    try:
        with open(p, 'r', encoding='utf-8', errors='ignore') as f:
            head = f.read(4096)
    except OSError:
        return None
    m = re.search(r'm_Script:\s*\{fileID:\s*-?\d+,\s*guid:\s*([0-9a-fA-F]{32})', head)
    return m.group(1).lower() if m else None


def read_field(p, field):
    try:
        with open(p, 'r', encoding='utf-8', errors='ignore') as f:
            c = f.read()
    except OSError:
        return None
    m = re.search(rf'^\s*{field}:\s*(\S+)\s*$', c, re.M)
    return m.group(1) if m else None


def read_obj_ref_guid(p, field):
    try:
        with open(p, 'r', encoding='utf-8', errors='ignore') as f:
            c = f.read()
    except OSError:
        return None
    m = re.search(rf'{re.escape(field)}:\s*\{{[^}}]*?guid:\s*([0-9a-fA-F]{{32}})', c)
    return m.group(1).lower() if m else None


def replace_meta_guid(meta_path, new_guid):
    with open(meta_path, 'r', encoding='utf-8') as f:
        c = f.read()
    new_c, n = re.subn(r'^guid:\s*[0-9a-fA-F]{32}\s*$',
                       f'guid: {new_guid}', c, count=1, flags=re.M)
    if n == 0:
        raise RuntimeError(f'no guid line in {meta_path}')
    with open(meta_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new_c)


def replace_ref_guid(p, field, new_guid):
    with open(p, 'r', encoding='utf-8') as f:
        c = f.read()
    new_c, n = re.subn(
        rf'({re.escape(field)}:\s*\{{[^}}]*?guid:\s*)[0-9a-fA-F]{{32}}',
        rf'\g<1>{new_guid}', c, count=1)
    if n == 0:
        new_c, n = re.subn(rf'^(\s*{re.escape(field)}:\s*)[0-9a-fA-F]{{32}}(\s*)$',
                           rf'\g<1>{new_guid}\g<2>', c, count=1, flags=re.M)
    if n == 0:
        raise RuntimeError(f'field {field} not found in {p}')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new_c)


# ---------- Phase 0 ----------
def resolve_type_guids(pkg_cache):
    print("\n" + "=" * 70)
    print("Phase 0: Resolve script-type GUIDs from PackageCache")
    print("=" * 70)

    wanted = {
        'LocalizationSettings':  'LocalizationSettings.cs.meta',
        'StringTableCollection': 'StringTableCollection.cs.meta',
        'SharedTableData':       'SharedTableData.cs.meta',
        'StringTable':           'StringTable.cs.meta',
        'Locale':                'Locale.cs.meta',
    }

    result = {}
    if not os.path.isdir(pkg_cache):
        print(f"  [!] PackageCache not found: {pkg_cache}")
        return result

    for dp, _, fns in os.walk(pkg_cache):
        if 'localization' not in dp.lower():
            continue
        for fn in fns:
            if fn not in wanted.values():
                continue
            key = [k for k, v in wanted.items() if v == fn][0]
            if key in result:
                continue
            g = read_meta_guid(os.path.join(dp, fn))
            if g:
                result[key] = g
                print(f"  {key:22s} {g}")

    return result


# ---------- Phase 1 ----------
def phase1_move(assets, settings_guid):
    print("\n" + "=" * 70)
    print("Phase 1: Move localization out of Resources")
    print("=" * 70)

    if not settings_guid:
        print("  [!] LocalizationSettings GUID not resolved")
        return None

    settings = []
    for dp, _, fns in os.walk(assets):
        for fn in fns:
            if not fn.endswith('.asset'):
                continue
            p = os.path.join(dp, fn)
            if read_script_guid(p) == settings_guid:
                settings.append(p)

    if not settings:
        print("  [!] LocalizationSettings asset not found")
        return None

    assets_root = os.path.normpath(assets)
    for sf in settings:
        parts = sf.split(os.sep)
        if 'Resources' not in parts:
            print(f"  [OK] Already outside Resources: "
                  f"{os.path.relpath(sf, os.path.dirname(assets_root))}")
            return os.path.dirname(sf)

        folder = os.path.dirname(sf)
        folder_name = os.path.basename(folder)
        dst = os.path.join(assets_root, folder_name)
        if os.path.exists(dst):
            print(f"  [!] Target already exists: "
                  f"{os.path.relpath(dst, os.path.dirname(assets_root))}")
            return dst

        print(f"  Move: {os.path.relpath(folder, os.path.dirname(assets_root))}")
        print(f"     -> {os.path.relpath(dst, os.path.dirname(assets_root))}")
        shutil.move(folder, dst)
        if os.path.exists(folder + '.meta'):
            shutil.move(folder + '.meta', dst + '.meta')

        parent = os.path.dirname(folder)
        while parent and parent != assets_root:
            try:
                if not os.listdir(parent):
                    if os.path.exists(parent + '.meta'):
                        os.remove(parent + '.meta')
                    os.rmdir(parent)
                    parent = os.path.dirname(parent)
                else:
                    break
            except OSError:
                break
        return dst
    return None


# ---------- Phase 2 ----------
def phase2_scan(loc_dir, guids):
    print("\n" + "=" * 70)
    print("Phase 2: Scan tables")
    print("=" * 70)

    shared, colls, tables = {}, {}, {}
    for dp, _, fns in os.walk(loc_dir):
        for fn in fns:
            if not fn.endswith('.asset'):
                continue
            p = os.path.join(dp, fn)
            meta = p + '.meta'
            if not os.path.exists(meta):
                continue
            sg = read_script_guid(p)
            mg = read_meta_guid(meta)

            if sg == guids.get('SharedTableData'):
                tn = read_field(p, 'm_TableCollectionName')
                if tn:
                    shared[tn] = {
                        'path': p, 'meta': meta, 'meta_guid': mg,
                        'tcguid': (read_field(p, 'm_TableCollectionNameGuidString') or '').lower(),
                    }
            elif sg == guids.get('StringTableCollection'):
                stem = os.path.splitext(fn)[0]
                colls[stem] = {'path': p, 'meta': meta, 'meta_guid': mg}
            elif sg == guids.get('StringTable'):
                m = re.match(r'(.+)_(\w+)\.asset$', fn)
                if m:
                    tables.setdefault(m.group(1), {})[m.group(2)] = {
                        'path': p, 'meta': meta, 'meta_guid': mg,
                    }

    print(f"  SharedData: {len(shared)}   Collections: {len(colls)}   "
          f"StringTables: {sum(len(v) for v in tables.values())}")
    return shared, colls, tables


# ---------- Phase 3 ----------
def phase3_targets(assets, loc_dir, shared):
    print("\n" + "=" * 70)
    print("Phase 3: Determine target GUID per table")
    print("=" * 70)

    scene_guids = set()
    for dp, _, fns in os.walk(assets):
        if dp == loc_dir or dp.startswith(loc_dir + os.sep):
            continue
        for fn in fns:
            if not fn.endswith(('.unity', '.prefab')):
                continue
            p = os.path.join(dp, fn)
            try:
                with open(p, 'r', encoding='utf-8', errors='ignore') as f:
                    c = f.read()
            except OSError:
                continue
            for m in re.finditer(r'm_TableCollectionName:\s*GUID:([0-9a-f]{32})', c):
                scene_guids.add(m.group(1).lower())

    targets, unresolved = {}, []
    for tn, info in shared.items():
        meta, tc = info['meta_guid'], info['tcguid']
        if tc in scene_guids:
            targets[tn] = tc
            print(f"  {tn:15s} -> {tc}  (m_TCGuid in scene)")
        elif meta in scene_guids:
            targets[tn] = meta
            print(f"  {tn:15s} -> {meta}  (.meta in scene)")
        else:
            targets[tn] = meta
            unresolved.append(tn)
            print(f"  {tn:15s} -> {meta}  (no scene ref, keep)")

    if unresolved:
        print(f"\n  Note: {len(unresolved)} tables have no scene reference: "
              f"{', '.join(unresolved)}")
    return targets


# ---------- Phase 4 ----------
def build_collection_yaml(name, shared_guid, table_guids, stc_guid):
    lines = [
        '%YAML 1.1',
        '%TAG !u! tag:unity3d.com,2011:',
        '--- !u!114 &11400000',
        'MonoBehaviour:',
        '  m_ObjectHideFlags: 0',
        '  m_CorrespondingSourceObject: {fileID: 0}',
        '  m_PrefabInstance: {fileID: 0}',
        '  m_PrefabAsset: {fileID: 0}',
        '  m_GameObject: {fileID: 0}',
        '  m_Enabled: 1',
        '  m_EditorHideFlags: 0',
        f'  m_Script: {{fileID: 11500000, guid: {stc_guid}, type: 3}}',
        f'  m_Name: {name}',
        '  m_EditorClassIdentifier: ',
        f'  m_SharedTableData: {{fileID: 11400000, guid: {shared_guid}, type: 2}}',
        '  m_Tables:',
    ]
    for g in table_guids:
        lines.append(f'  - {{fileID: 11400000, guid: {g}, type: 2}}')
    lines += ['  m_Extensions: []', '  m_Group: String Table', '  references:', '    version: 1', '']
    return '\n'.join(lines)


def build_meta_yaml(guid):
    return (
        'fileFormatVersion: 2\n'
        f'guid: {guid}\n'
        'NativeFormatImporter:\n'
        '  externalObjects: {}\n'
        '  mainObjectFileID: 11400000\n'
        '  userData: \n'
        '  assetBundleName: \n'
        '  assetBundleVariant: \n'
    )


def phase4_collections(shared, tables, targets, stc_guid):
    print("\n" + "=" * 70)
    print("Phase 4: Generate or repair Collections")
    print("=" * 70)

    if not stc_guid:
        print("  [!] StringTableCollection type GUID not resolved")
        return

    for tn in sorted(shared):
        sd = shared[tn]
        target = targets.get(tn)
        if not target:
            continue
        langs = tables.get(tn, {})
        if not langs:
            print(f"  [!] {tn}: no StringTables, skip")
            continue

        sd_dir = os.path.dirname(sd['path'])
        coll_path = os.path.join(sd_dir, f'{tn}.asset')
        coll_meta = coll_path + '.meta'

        existed = os.path.exists(coll_path)
        existing_guid = read_meta_guid(coll_meta) if os.path.exists(coll_meta) else None

        complete = False
        if existed:
            try:
                with open(coll_path, 'r', encoding='utf-8', errors='ignore') as f:
                    c = f.read()
                has_shared = re.search(
                    rf'm_SharedTableData:\s*\{{[^}}]*guid:\s*{re.escape(target)}', c
                ) is not None
                n_entries = len(re.findall(r'^\s+-\s+\{fileID: 11400000, guid:', c, re.M))
                if has_shared and n_entries == len(langs):
                    complete = True
            except OSError:
                pass

        if complete:
            print(f"  [OK] {tn} ({len(langs)} tables)")
            continue

        table_guids = [langs[lang]['meta_guid'] for lang in sorted(langs)]
        with open(coll_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(build_collection_yaml(tn, target, table_guids, stc_guid))

        if not existing_guid:
            existing_guid = secrets.token_hex(16)
            with open(coll_meta, 'w', encoding='utf-8', newline='\n') as f:
                f.write(build_meta_yaml(existing_guid))

        verb = 'Rebuilt' if existed else 'Generated'
        print(f"  {verb}: {tn:15s} ({len(table_guids)} tables)  GUID={existing_guid}")


# ---------- Phase 5 ----------
def phase5_align(shared, tables, targets):
    print("\n" + "=" * 70)
    print("Phase 5: Align all GUIDs")
    print("=" * 70)

    for tn, info in shared.items():
        target = targets.get(tn)
        if not target:
            continue

        if info['meta_guid'] != target:
            replace_meta_guid(info['meta'], target)
            print(f"  {tn}: .meta {info['meta_guid']} -> {target}")
            info['meta_guid'] = target

        if info['tcguid'] != target:
            try:
                replace_ref_guid(info['path'], 'm_TableCollectionNameGuidString', target)
                print(f"  {tn}: m_TCGuid {info['tcguid']} -> {target}")
            except Exception as e:
                print(f"  [!] {tn}: m_TCGuid: {e}")

        langs = tables.get(tn, {})
        fixed = 0
        for lang, sp in langs.items():
            cur = read_obj_ref_guid(sp['path'], 'm_SharedData')
            if cur and cur != target:
                try:
                    replace_ref_guid(sp['path'], 'm_SharedData', target)
                    fixed += 1
                except Exception as e:
                    print(f"  [!] {tn}/{lang}: {e}")
        if fixed:
            print(f"  {tn}: fixed {fixed}/{len(langs)} StringTables m_SharedData")


# ---------- Phase 6 ----------
def phase6_addressables(assets, loc_dir):
    print("\n" + "=" * 70)
    print("Phase 6: Sync Addressable group")
    print("=" * 70)

    group_file = os.path.join(assets, 'AddressableAssetsData', 'AssetGroups',
                              'Default Local Group.asset')
    if not os.path.exists(group_file):
        addr_dir = os.path.dirname(group_file)
        group_file = None
        if os.path.isdir(addr_dir):
            for fn in os.listdir(addr_dir):
                if fn.endswith('.asset'):
                    p = os.path.join(addr_dir, fn)
                    try:
                        with open(p, 'r', encoding='utf-8', errors='ignore') as f:
                            if re.search(r'^\s*m_GroupName:\s*Default\s*$', f.read(), re.M):
                                group_file = p
                                break
                    except OSError:
                        continue

    if not group_file:
        print("  [!] Default Local Group not found")
        return

    print(f"  Group: {os.path.relpath(group_file, os.path.dirname(assets))}")

    # Collect every .asset and .prefab in localization
    files = []
    for dp, _, fns in os.walk(loc_dir):
        for fn in fns:
            if not fn.endswith(('.asset', '.prefab')):
                continue
            p = os.path.join(dp, fn)
            g = read_meta_guid(p + '.meta')
            if not g:
                continue
            addr = 'Assets/' + os.path.relpath(p, assets).replace(os.sep, '/')
            files.append((g, addr))

    print(f"  Localization assets: {len(files)}")

    with open(group_file, 'r', encoding='utf-8') as f:
        content = f.read()
    lines = content.splitlines()

    # Parse existing entries
    existing = {}
    i = 0
    while i < len(lines):
        m = re.match(r'^\s*-\s*m_GUID:\s*([0-9a-fA-F]{32})\s*$', lines[i])
        if m:
            guid = m.group(1).lower()
            j = i + 1
            addr = None
            while j < len(lines):
                if lines[j].lstrip().startswith('- m_GUID:') or lines[j].lstrip().startswith('- {fileID:'):
                    break
                am = re.match(r'^\s*m_Address:\s*(.+?)\s*$', lines[j])
                if am:
                    addr = am.group(1).strip().replace('\\', '/')
                    break
                j += 1
            if addr:
                existing[addr] = guid
            i = j + 1
        else:
            i += 1

    updates = {}
    adds = []
    for guid, addr in files:
        if addr in existing:
            if existing[addr] != guid:
                updates[existing[addr]] = guid
        else:
            adds.append((guid, addr))

    out = []
    for line in lines:
        m = re.match(r'^(\s*-\s*m_GUID:\s*)([0-9a-fA-F]{32})(\s*)$', line)
        if m:
            prefix, old_guid, suffix = m.groups()
            new_guid = updates.get(old_guid.lower(), old_guid)
            out.append(f"{prefix}{new_guid}{suffix}")
        else:
            out.append(line)

    if adds:
        for idx, line in enumerate(out):
            m = re.match(r'^(\s*)m_SerializeEntries:(\s*\[\])?\s*$', line)
            if m:
                indent = m.group(1)
                new_entries = []
                for guid, addr in adds:
                    new_entries.append(f'{indent}- m_GUID: {guid}')
                    new_entries.append(f'{indent}  m_Address: {addr}')
                    new_entries.append(f'{indent}  m_ReadOnly: 0')
                    new_entries.append(f'{indent}  m_SerializedLabels: []')
                    new_entries.append(f'{indent}  FlaggedDuringContentUpdateRestriction: 0')
                if m.group(2):
                    out[idx] = f'{indent}m_SerializeEntries:'
                out = out[:idx + 1] + new_entries + out[idx + 1:]
                break

    new_content = '\n'.join(out) + '\n'
    if new_content != content:
        with open(group_file, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new_content)
        print(f"  Updated {len(updates)} m_GUID, added {len(adds)} entries")
    else:
        print("  No changes needed")

# ---------- Phase 7 ----------
def phase7_delete_assetbundles_localization(assets):
    print("\n" + "=" * 70)
    print("Phase 7: Delete Localization folders under Assets/AssetBundles")
    print("=" * 70)

    bundle_root = os.path.normpath(os.path.join(assets, 'AssetBundles'))
    if not os.path.isdir(bundle_root):
        print(f"  [skip] AssetBundles not found")
        return

    # Collect every folder named "Localization" anywhere under AssetBundles
    targets = []
    for dp, dns, _ in os.walk(bundle_root):
        hits = [d for d in dns if d.lower() == 'localization']
        for d in hits:
            targets.append(os.path.join(dp, d))
        # Prevent os.walk from descending into them (children will be removed with rmtree)
        dns[:] = [d for d in dns if d.lower() != 'localization']

    if not targets:
        print("  [skip] No Localization folders found")
        return

    print(f"  Found {len(targets)} Localization folder(s):")
    for t in targets:
        print(f"    {os.path.relpath(t, os.path.dirname(assets))}")

    _get_tk()
    if not messagebox.askyesno(
        "Delete AssetBundles/Localization",
        f"Found {len(targets)} 'Localization' folder(s) under Assets/AssetBundles.\n\n"
        "Delete them (including their .meta) and clean up any parent folders "
        "that become empty?\n\n"
        "Only proceed if you have already verified Localization works in Unity.",
    ):
        print("  User declined. Skipped.")
        return

    assets_norm = os.path.normpath(assets)
    for t in targets:
        try:
            if os.path.isdir(t):
                shutil.rmtree(t)
                print(f"  Deleted: {os.path.relpath(t, os.path.dirname(assets))}")
            meta = t + '.meta'
            if os.path.exists(meta):
                os.remove(meta)
                print(f"  Deleted: {os.path.relpath(meta, os.path.dirname(assets))}")
        except OSError as e:
            print(f"  [!] Failed to delete {t}: {e}")
            continue

        # Walk up and remove empty parents, stopping at AssetBundles root or Assets
        parent = os.path.dirname(t)
        while True:
            pn = os.path.normpath(parent)
            if pn == bundle_root or pn == assets_norm or not os.path.isdir(parent):
                break
            try:
                entries = [e for e in os.listdir(parent) if not e.endswith('.meta')]
            except OSError:
                break
            if entries:
                break
            try:
                for e in os.listdir(parent):
                    if e.endswith('.meta'):
                        os.remove(os.path.join(parent, e))
                os.rmdir(parent)
                print(f"  Deleted empty parent: "
                      f"{os.path.relpath(parent, os.path.dirname(assets))}")
                parent = os.path.dirname(parent)
            except OSError:
                break

    print("  Phase 7 done.")

# ---------- main ----------
def main():
    exported = select_project_folder()
    if not exported:
        print("No project folder selected.")
        return
    assets = os.path.join(exported, 'Assets')
    pkg_cache = os.path.join(exported, 'Library', 'PackageCache')

    if not os.path.isdir(assets):
        messagebox.showerror("Error", f"Assets not found: {assets}")
        return
    if not os.path.isdir(pkg_cache):
        messagebox.showerror("Error", f"PackageCache not found: {pkg_cache}")
        return

    guids = resolve_type_guids(pkg_cache)
    required = ['LocalizationSettings', 'StringTableCollection',
                'SharedTableData', 'StringTable', 'Locale']
    missing = [k for k in required if k not in guids]
    if missing:
        messagebox.showerror(
            "Missing type GUIDs",
            "Could not find these .cs.meta in PackageCache:\n" + "\n".join(missing)
            + "\n\nIs the Localization package installed?",
        )
        return

    loc_dir = phase1_move(assets, guids['LocalizationSettings'])
    if not loc_dir:
        return

    shared, _colls, tables = phase2_scan(loc_dir, guids)
    if not shared:
        print("\n[!] No SharedData found")
        return

    targets = phase3_targets(assets, loc_dir, shared)
    phase4_collections(shared, tables, targets, guids['StringTableCollection'])
    phase5_align(shared, tables, targets)
    phase6_addressables(assets, loc_dir)
